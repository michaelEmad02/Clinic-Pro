// ────────────────────────────────────────────────────────
// IVoiceExtractionService — واجهة استخراج البيانات الصوتية الموحدة
// تقدم عقداً مركزياً لتحليل النصوص المنطوقة لكافة شاشات التطبيق
// (المصروفات، المرضى، الفواتير، المواعيد)
// ────────────────────────────────────────────────────────

enum ExtractionTarget {
  /// استخراج بيانات مصروف (مبلغ، تصنيف، بيان)
  expense,

  /// استخراج بيانات مريض (اسم، هاتف، عمر، جنس)
  patient,

  /// استخراج بيانات فاتورة (مبلغ، خصم، طريقة دفع)
  invoice,

  /// استخراج بيانات موعد (تاريخ، وقت، نوع الزيارة)
  appointment,

  /// استخراج بيانات روشتة طبية (تشخيص، أدوية، جرعات، استشارة، ملاحظات)
  prescription,
}

abstract class IVoiceExtractionService {
  /// تحليل النص واستخراج خريطة البيانات بحسب نوع الشاشة المستهدفة
  /// - [text]: النص المنطوق بعد تحويله من الصوت
  /// - [target]: نوع الهدف (مصروف، مريض، فاتورة، إلخ)
  /// - [extraContext]: سياق إضافي اختياري (مثل قائمة الفئات المتاحة للمصروفات)
  Future<Map<String, dynamic>> extractData({
    required String text,
    required ExtractionTarget target,
    Map<String, dynamic>? extraContext,
  });
}
